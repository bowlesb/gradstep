// Chat answers as HTML, entirely in this bundle (no CDN): Markdown by markdown-it with raw HTML and images off, math
// (`\(…\)`, `\[…\]`, `$…$`, `$$…$$`, environments) by Temml as MathML with `trust` off, then an allowlist sanitizer
// over the DOM as defense in depth (answers are model output that a paper's text could steer).
import MarkdownIt from 'markdown-it';
import temml from 'temml';
const md = new MarkdownIt({ html: false, linkify: true, typographer: false, breaks: false });
md.disable(['image']);
export { safeLink } from './links';
import { safeLink } from './links';
md.validateLink = url => safeLink(url) !== null;
const defaultLink = md.renderer.rules.link_open ?? ((tokens, i, options, _env, self) => self.renderToken(tokens, i, options));
md.renderer.rules.link_open = (tokens, i, options, env, self) => {
  tokens[i].attrSet('target', '_blank');
  tokens[i].attrSet('rel', 'noopener noreferrer');
  return defaultLink(tokens, i, options, env, self);
};

const escape = (s: string) => s.replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

export function renderMath(body: string, display: boolean): string {
  try {
    return temml.renderToString(body, { displayMode: display, throwOnError: false, trust: false, annotate: false, maxExpand: 1000, maxSize: [100, 100] });
  } catch { return `<code class="math-source">${escape(body)}</code>`; }
}

// Parse math as Markdown tokens, never by replacing HTML placeholders inside attributes or code.
md.inline.ruler.before('escape', 'gradstep_math', (state, silent) => {
  const start = state.pos, source = state.src;
  if (source[start] !== '\\' && source[start] !== '$') return false;
  let open = '', close = '', display = false, environment = false;
  if (source.startsWith('\\[', start)) { open = '\\['; close = '\\]'; display = true; }
  else if (source.startsWith('\\(', start)) { open = '\\('; close = '\\)'; }
  else if (source.startsWith('$$', start)) { open = close = '$$'; display = true; }
  else if (source[start] === '$' && !/\s/.test(source[start + 1] ?? ' ')) { open = close = '$'; }
  else {
    const match = /^\\begin\{([A-Za-z*]{1,40})\}/.exec(source.slice(start, start + 50));
    if (!match) return false;
    open = match[0]; close = `\\end{${match[1]}}`; display = environment = true;
  }
  let end = source.indexOf(close, start + open.length);
  while (end >= 0 && (source[end - 1] === '\\' || (open === '$' && (/\s/.test(source[end - 1]) || /[0-9]/.test(source[end + 1] ?? ''))))) end = source.indexOf(close, end + close.length);
  if (end < 0) {
    if (!silent) { const token = state.push('text', '', 0); token.content = source.slice(start); }
    state.pos = source.length; return true;
  }
  const body = source.slice(environment ? start : start + open.length, environment ? end + close.length : end);
  if (!silent) { const token = state.push('gradstep_math', 'math', 0); token.content = body; token.meta = { display }; }
  state.pos = end + close.length; return true;
});
// Grounded citations: an answer about a numbered paper (reader-local-context-v2) cites blocks as `[¶12]`; each becomes a
// small control that the chat pane turns into a jump to that passage. Any other bracketed text is left to Markdown.
md.inline.ruler.before('escape', 'gradstep_cite', (state, silent) => {
  const source = state.src, start = state.pos;
  if (source.charCodeAt(start) !== 0x5b /* [ */ || source[start + 1] !== '¶') return false;
  const match = /^\[¶(\d{1,5})\]/.exec(source.slice(start, start + 9));
  if (!match) return false;
  if (!silent) { const token = state.push('gradstep_cite', 'span', 0); token.content = String(Number(match[1])); }
  state.pos = start + match[0].length; return true;
});
md.renderer.rules.gradstep_cite = (tokens, i) => {
  const n = /^\d{1,5}$/.test(tokens[i].content) ? tokens[i].content : null;
  return n ? `<span class="cite" data-cite="${n}" role="link" tabindex="0" title="Go to passage ¶${n}">¶${n}</span>` : '';
};
md.renderer.rules.gradstep_math = (tokens, i, _options, env) => {
  if (!env) return '';
  env.formulas = (typeof env.formulas === 'number' ? env.formulas : 0) + 1;
  const token = tokens[i];
  if (token.content.length > 12_000 || (env.formulas as number) > 500) return `<code class="math-source">${escape(token.content)}</code>`;
  return renderMath(token.content, token.meta?.display === true);
};

/** No HTML, embedded media, remote fonts or script execution. Math is generated by our bundled Temml. */
export function renderMarkdown(text: string, _streaming = false): string {
  const html = md.render(text.slice(0, 200_000), {});
  return typeof DOMParser === 'function' ? sanitize(html) : html;
}

// ---------- Allowlist sanitizer ----------

const HTML_TAGS = new Set(['p', 'br', 'hr', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'strong', 'em', 'b', 'i', 's', 'del', 'code', 'pre', 'blockquote', 'ul', 'ol',
  'li', 'table', 'thead', 'tbody', 'tr', 'th', 'td', 'a', 'span', 'div', 'sup', 'sub']);
const MATH_TAGS = new Set(['math', 'semantics', 'mrow', 'mi', 'mn', 'mo', 'ms', 'mtext', 'mspace', 'msub', 'msup', 'msubsup', 'mfrac', 'msqrt', 'mroot', 'mover',
  'munder', 'munderover', 'mtable', 'mtr', 'mtd', 'mstyle', 'mpadded', 'mphantom', 'menclose', 'merror', 'mlabeledtr', 'mmultiscripts', 'mprescripts', 'none']);
const MATH_ATTRIBUTES = new Set(['display', 'displaystyle', 'mathvariant', 'mathsize', 'mathcolor', 'mathbackground', 'stretchy', 'fence', 'separator', 'lspace',
  'rspace', 'width', 'height', 'depth', 'voffset', 'columnalign', 'rowalign', 'columnspacing', 'rowspacing', 'columnlines', 'rowlines', 'frame', 'scriptlevel',
  'accent', 'accentunder', 'movablelimits', 'linethickness', 'form', 'symmetric', 'largeop', 'minsize', 'maxsize', 'notation', 'class']);
const MATHML = 'http://www.w3.org/1998/Math/MathML';

export function sanitize(html: string): string {
  const source = new DOMParser().parseFromString(`<!doctype html><body>${html}`, 'text/html').body;
  const target = document.implementation.createHTMLDocument('');
  const copy = (node: Node, parent: Node) => {
    if (node.nodeType === Node.TEXT_NODE) { parent.appendChild(target.createTextNode(node.textContent ?? '')); return; }
    if (node.nodeType !== Node.ELEMENT_NODE) return;
    const element = node as Element, tag = element.localName, math = element.namespaceURI === MATHML;
    if (math ? !MATH_TAGS.has(tag) : !HTML_TAGS.has(tag)) {
      // Unknown containers keep their text; scripts, styles and the like are dropped whole.
      if (!['script', 'style', 'iframe', 'object', 'embed', 'template', 'annotation', 'annotation-xml', 'svg', 'foreignobject'].includes(tag)) for (const child of element.childNodes) copy(child, parent);
      return;
    }
    const out = math ? target.createElementNS(MATHML, tag) : target.createElement(tag);
    for (const attribute of element.attributes) {
      const name = attribute.name.toLowerCase(), value = attribute.value;
      if (math) {
        if (MATH_ATTRIBUTES.has(name)) out.setAttribute(name, value);
        else if (name === 'style') {
          // Only typesetting declarations, never positioning across app chrome or loading resources.
          const allowed = /^(?:color|background-color|font-(?:size|family|weight|style)|line-height|vertical-align|text-align|display|width|height|min-width|max-width|margin(?:-(?:left|right|top|bottom))?|padding(?:-(?:left|right|top|bottom))?|border(?:-(?:left|right|top|bottom))?(?:-(?:width|style|color))?)$/;
          const declarations = value.split(';').filter(d => { const i = d.indexOf(':'); return i > 0 && allowed.test(d.slice(0, i).trim()) && !/url|expression|@|\\|[\u0000-\u001f]/i.test(d.slice(i + 1)); });
          if (declarations.length) out.setAttribute('style', declarations.join(';'));
        }
      } else if (tag === 'a' && name === 'href') {
        const href = safeLink(value); if (href) out.setAttribute('href', href);
      } else if ((name === 'class' && ['code', 'span', 'div'].includes(tag)) || (name === 'start' && tag === 'ol') || (name === 'style' && (tag === 'th' || tag === 'td') && /^text-align:(left|right|center)$/.test(value))) {
        out.setAttribute(name, value);
      } else if (tag === 'span' && element.classList.contains('cite') && ((name === 'data-cite' && /^\d{1,5}$/.test(value)) || (name === 'role' && value === 'link')
        || (name === 'tabindex' && value === '0') || (name === 'title' && /^Go to passage ¶\d{1,5}$/.test(value)))) {
        out.setAttribute(name, value);
      }
    }
    if (tag === 'a') { out.setAttribute('target', '_blank'); out.setAttribute('rel', 'noopener noreferrer'); }
    parent.appendChild(out);
    for (const child of element.childNodes) copy(child, out);
  };
  const box = target.createElement('div');
  for (const child of source.childNodes) copy(child, box);
  return box.innerHTML;
}
