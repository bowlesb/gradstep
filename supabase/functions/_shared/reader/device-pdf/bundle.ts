export interface DevicePDFBundle {
  manifestBytes: Uint8Array; manifestSHA256: string; members: Map<string, Uint8Array>;
  summary: Record<string, unknown>; trace?: unknown;
}

const isHex64 = (v: unknown): v is string => typeof v === 'string' && /^[a-f0-9]{64}$/.test(v);

/** `onPreview`: with a host that recognises in the background, a complete bundle made before the formulas are read (each
 * one its image) is handed over first, so the reader can show the paper while the recogniser finishes. */
export function composeDevicePDFReader(input: DevicePDFInput, host: DevicePDFHost, onPreview?: (bundle: DevicePDFBundle) => void): DevicePDFBundle {
  check(input && typeof input === 'object' && input.pdf && isHex64(input.pdf.sha256) && Number.isSafeInteger(input.pdf.bytes) && input.pdf.bytes > 0, 'device_pdf_input');
  check(input.tagger && typeof input.tagger.threshold === 'number' && Number.isSafeInteger(input.tagger.max_len) && input.tagger.font_vocab && input.tagger.char_vocab && input.tagger.font_prior, 'device_pdf_tagger');
  const models = (Array.isArray(input.models) ? input.models : []).slice(0, 8).map(m => ({ role: String(m.role).slice(0, 64), id: String(m.id).slice(0, 128), sha256: String(m.sha256).slice(0, 64) }));
  const paper = input.paper && typeof input.paper.source_id === 'string' && Number.isSafeInteger(input.paper.revision) && input.paper.revision > 0
    ? { source_id: input.paper.source_id.slice(0, 64), revision: input.paper.revision } : undefined;
  const started = Date.now();
  const reading = read(input, host);
  if (onPreview && reading.submissions.length) onPreview(assemble(input, host, reading, models, paper, started));
  settle(reading, host);
  gate(reading);
  return assemble(input, host, reading, models, paper, started);
}

function assemble(input: DevicePDFInput, host: DevicePDFHost, reading: Reading, models: { role: string; id: string; sha256: string }[],
  paper: { source_id: string; revision: number } | undefined, started: number): DevicePDFBundle {
  const fallbackTitle = (typeof input.title === 'string' && input.title.trim()) || reading.trace.title;
  const emitted = emit(reading, host, fallbackTitle);
  const { index } = emitted;
  const html = htmlPrefix(index.title) + emitted.top.map(render).join('') + HTML_SUFFIX;
  const htmlBytes = utf8(html);
  check(htmlBytes.length <= LIMITS.htmlBytes, 'html_limit');
  validateHTML(htmlBytes, index, new Map([...emitted.images.values()].map(i => [i.path, { width: i.width, height: i.height }])), false, true);

  // The reference's index completed: each equation's reading, gate and source region.
  const formulas = reading.formulas;
  for (const row of reading.trace.equations) {
    const f = formulas.get(row.id as string)!;
    row.latex = f.latex || '\\text{?}';
    row.confidence = pyRound(f.confidence, 4);
    row.rendered = f.rendered;
    row.source = { page: f.page, box: f.box.map(v => pyRound(v, 1)), ...(f.baseline !== undefined ? { baseline: pyRound(f.baseline, 1) } : {}) };
  }
  const rendered = reading.committed.filter(id => formulas.get(id)!.rendered).length;
  const summary = {
    pages: input.pages, blocks: index.blocks.length, headings: index.headings.length, equations: reading.committed.length, rendered, transcribed: reading.committed.filter(id => formulas.get(id)!.transcribed).length,
    figures: index.figures.length, images: emitted.images.size, unowned: reading.unowned,
    recognition_failures: reading.recognitionFailures, degraded: emitted.degraded, seconds: pyRound((Date.now() - started) / 1000, 1),
    warnings: reading.warnings.slice(0, 20),
  };
  const warnings = [...reading.warnings];
  const d = emitted.degraded;
  if (d.formulaText) warnings.push(`${d.formulaText} formulas shown as LaTeX text (image budget)`);
  if (d.figuresScaled) warnings.push(`${d.figuresScaled} figures scaled down (image budget)`);
  if (d.figuresOmitted) warnings.push(`${d.figuresOmitted} figures shown by their captions (image budget or crop failure)`);
  if (d.equationLimit) warnings.push(`${d.equationLimit} formulas past the equation limit shown as text`);
  if (d.imageFailures) warnings.push(`${d.imageFailures} crops the device could not make`);
  const provenance = canonicalBytes({
    format: DEVICE_PDF_PROVENANCE_FORMAT,
    source: { kind: DEVICE_PDF_SOURCE_KIND, pdf_sha256: input.pdf.sha256, pdf_bytes: input.pdf.bytes, pages: input.pages, ...(paper ? { paper } : {}) },
    models,
    gate: { inline: { statistic: 'min token probability', threshold: GATE }, display: { statistic: 'second-lowest token probability', threshold: reading.displayGate } },
    adapter: { id: DEVICE_PDF_RENDERER_ID, converter: DEVICE_PDF_CONVERTER_VERSION, revision: DEVICE_PDF_PORT_REVISION, build_sha256: DEVICE_PDF_BUILD_SHA256 },
    // The time it took is not part of the bundle: one PDF read twice by one converter is the same bundle.
    summary: { ...summary, warnings: undefined, seconds: undefined },
    warnings: warnings.slice(0, 200).map(w => w.slice(0, 300)),
    // Per equation: confidence, whether it rendered, and its source region (page, box in points, baseline).
    equations: reading.committed.map(id => { const f = formulas.get(id)!; return [id, pyRound(f.confidence, 4), f.rendered ? 1 : 0, f.page, ...f.box.map(v => pyRound(v, 1)), f.baseline === undefined ? -1 : pyRound(f.baseline, 1)]; }),
    // Per figure shown: its id, page and crop in points (the apps zoom out of the crop onto the PDF on the device).
    figures: emitted.figureRegions,
  });
  check(provenance.length <= 2 * 1024 * 1024, 'provenance_limit');
  const members = new Map<string, Uint8Array>([['index.html', htmlBytes], ['reader.json', canonicalBytes(index)], ['reader.css', utf8(DEVICE_PDF_CSS)],
    ['provenance.json', provenance], ['NOTICE.txt', utf8(DEVICE_PDF_NOTICES + `\n\nSource: ${input.pdf.name.slice(0, 200).replace(/[\u0000-\u001f\u007f]/g, '')} (${input.pdf.bytes} bytes, sha256 ${input.pdf.sha256}), prepared on the reader's device.\n`)]]);
  for (const image of emitted.images.values()) members.set(image.path, image.bytes);
  check(members.get('reader.json')!.length <= LIMITS.indexBytes, 'index_limit');
  const fixed: Record<string, [string, string]> = { 'index.html': ['html', 'text/html'], 'reader.json': ['index', 'application/json'],
    'reader.css': ['style', 'text/css'], 'provenance.json': ['provenance', 'application/json'], 'NOTICE.txt': ['notice', 'text/plain'] };
  let total = 0;
  const entries = [...members].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([path, bytes]) => {
    total += bytes.length; check(bytes.length > 0 && bytes.length <= LIMITS.memberBytes && total <= LIMITS.bundleBytes, 'bundle_limit');
    const image = emitted.images.get(path);
    return { path, role: image ? 'image' : fixed[path][0], media_type: image ? 'image/png' : fixed[path][1], bytes: bytes.length,
      sha256: sha256Hex(bytes), ...(image ? { width: image.width, height: image.height } : {}) };
  });
  check(entries.length <= LIMITS.members, 'bundle_limit');
  const manifestBytes = canonicalBytes({ format: BUNDLE_FORMAT, renderer: { id: DEVICE_PDF_RENDERER_ID, build_sha256: DEVICE_PDF_BUILD_SHA256 },
    source: { kind: DEVICE_PDF_SOURCE_KIND, sha256: input.pdf.sha256, provenance_path: 'provenance.json' },
    entrypoint: 'index.html', index_path: 'reader.json', members: entries });
  check(manifestBytes.length <= LIMITS.manifestBytes, 'manifest_limit');
  return { manifestBytes, manifestSHA256: sha256Hex(manifestBytes), members, summary: { ...summary, bytes: total },
    ...(input.trace ? { trace: reading.trace } : {}) };
}
